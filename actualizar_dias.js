async function actualizarDiasFijos() {
    console.log('⚡ Iniciando actualización de Días Fijos...');
    let connection;
    try {
        connection = await mysql.createConnection(dbConfig);
        let actualizados = 0;
        let noEncontrados = [];

        for (const [nombreComp, diasFijos] of Object.entries(datosManuales)) {
            const [rows] = await connection.execute(
                "SELECT id FROM usuarios WHERE CONCAT(apellido, ' ', nombre) LIKE ? OR CONCAT(nombre, ' ', apellido) LIKE ?", 
                [`%${nombreComp}%`, `%${nombreComp}%`]
            );
            
            if (rows.length > 0) {
                const usuarioId = rows[0].id;
                await connection.execute(
                    'UPDATE usuarios SET dias_fijos = ? WHERE id = ?', 
                    [diasFijos, usuarioId]
                );
                actualizados++;
            } else {
                noEncontrados.push(nombreComp);
            }
        }
        
        console.log(`\n✅ ¡Éxito! Se actualizaron los días fijos de ${actualizados} alumnos.`);
        
        if (noEncontrados.length > 0) {
            console.log(`\n⚠️ Hubo ${noEncontrados.length} alumnos que NO están creados en tu base de datos (o están escritos diferente):`);
            noEncontrados.forEach(n => console.log(` - ${n}`));
        }
        
    } catch (error) {
        console.error('❌ Error:', error);
    } finally {
        if (connection) await connection.end();
    }
}

